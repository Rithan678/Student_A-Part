    doc.moveDown();

    // Job Information
    const job = jobInfo[0];
    doc.fontSize(16).text('Job Details:', { underline: true });
    doc.fontSize(12)
       .text(`Job Title: ${job.title}`)
       .text(`Organization: ${job.organization_name}`)
       .text(`Location: ${job.location || 'N/A'}`)
       .text(`Job Type: ${job.job_type}`)
       .text(`Salary Range: ${job.salary_range || 'Not specified'}`)
       .text(`Report Generated: ${new Date().toLocaleDateString()}`)
       .text(`Generated by: ${job.owner_name}`);
    
    doc.moveDown();

    // Check if there are accepted applicants
    if (jobApplicants.length === 0) {
      doc.fontSize(14).text('No accepted applicants found for this job.', { align: 'center' });
      doc.end();
      return;
    }

    // Accepted Applicants Section
    doc.fontSize(16).text('Accepted Applicants:', { underline: true });
